def fix_file(path):
    with open(path, 'r', encoding='utf-8') as f:
        content = f.read()

    # Apply longer strings first to avoid partial matches
    for bad, good in sorted(MAP_CONFIG_FIXES.items(), key=lambda x: -len(x[0])):
        content = content.replace(bad, good)

    # Replace portal arrow (always surrounded by spaces in portal names)
    content = content.replace(' ??? ', ' → ')

    with open(path, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"Fixed: {path}")

